# src.models.sequence_layout
# ============================================================================
# Packed-sequence geometry shared by both attention branches. window_bounds lives
# with the softmax package; this module is the part every consumer of the PACKED LAYOUT
# needs, model or not.

@dataclass(frozen=True)
class SequenceLayout:
    seq_len: int
    video_start: int          # first video row in the packed sequence
    num_frames: int           # F: latent frames
    tokens_per_frame: int     # S: patched spatial tokens per latent frame (t-major order)

    # Patched spatial grid, S = frame_height * frame_width. 0 means "not supplied":
    # S alone cannot be factored back into a grid (1008 is 24x42, but also 16x63), so
    # anything that needs the volume shape — ShortConv — must be given it explicitly
    # rather than guessing. Everything else only ever needed the token count.
    frame_height: int = 0
    frame_width: int = 0

    # Where the PROMPT rows live. Distinct from `global_index` on purpose: that one
    # returns text+audio (everything the softmax keeps dense), while the linear branch's
    # text state must see the text and NOT the soundtrack. 0 = not supplied.
    text_start: int = 0
    text_len: int = 0

    @property
    def video_end(self):
        return self.video_start + self.num_frames * self.tokens_per_frame

    @property
    def text_range(self):
        if not self.text_len:
            raise ValueError(
                "this layout carries no text rows; pass text_indices=... to "
                "layout_from_indices (the linear branch's text state needs the prompt "
                "rows, and text+audio from global_index is not the same thing)"
            )
        return self.text_start, self.text_start + self.text_len

    @property
    def frame_size(self):
        if not (self.frame_height and self.frame_width):
            raise ValueError(
                "this layout carries no spatial grid; pass frame_size=(H, W) to "
                "layout_from_indices — a 3D convolution cannot infer it from S alone"
            )
        if self.frame_height * self.frame_width != self.tokens_per_frame:
            raise ValueError(f"grid {self.frame_height}x{self.frame_width} != "
                             f"{self.tokens_per_frame} tokens/frame")
        return self.frame_height, self.frame_width

    def global_index(self, device):
        """Indices of the non-video rows (text, audio). The diffusers port packs no
        padding, so every row is content."""
        idx = torch.arange(self.seq_len, device=device)
        return torch.cat([idx[:self.video_start], idx[self.video_end:]])


def layout_from_indices(video_indices: torch.Tensor, num_latent_frames: int,
                        tokens_per_frame: int, seq_len: int,
                        frame_size=None, text_indices=None) -> SequenceLayout:
    """Derive the layout from `build_packed_sequence` outputs. The t2va layout puts the
    target video rows contiguous and t-major at the end of the sequence; verify rather
    than assume, because everything downstream silently depends on it."""
    video_start = int(video_indices[0].item())
    if int(video_indices[-1].item()) - video_start + 1 != video_indices.numel():
        raise ValueError("video rows are not contiguous in the packed sequence")
    if video_indices.numel() != num_latent_frames * tokens_per_frame:
        raise ValueError(
            f"{video_indices.numel()} video rows != {num_latent_frames} frames x "
            f"{tokens_per_frame} tokens/frame"
        )
    height, width = frame_size or (0, 0)
    if frame_size and height * width != tokens_per_frame:
        raise ValueError(f"frame_size {height}x{width} != {tokens_per_frame} tokens/frame")
    text_start, text_len = 0, 0
    if text_indices is not None and text_indices.numel():
        text_start = int(text_indices[0].item())
        if int(text_indices[-1].item()) - text_start + 1 != text_indices.numel():
            raise ValueError("text rows are not contiguous in the packed sequence")
        text_len = int(text_indices.numel())
    return SequenceLayout(seq_len=seq_len, video_start=video_start,
                        num_frames=num_latent_frames, tokens_per_frame=tokens_per_frame,
                        frame_height=height, frame_width=width,
                        text_start=text_start, text_len=text_len)


# ============================================================================
# src.models.attention_gates
# ============================================================================
# OutputGate: the sigmoid gate BOTH branches put on their output.
#
# Shared on purpose -- the softmax side instantiates it per-head (init 0.99: the softmax
# branch IS the teacher at step 0) and the linear side per-channel with init="random" (a live
# low-rank path from step 0, matching fla's g_proj).

class OutputGate(nn.Module):
    """Sigmoid gate on a branch's output, zero-initialised so it starts at `init_value`.

    Both branches gate their output, but at different granularity:

      SOFTMAX (head_dim=None) one value per (token, head), broadcast over channels. The
            windowed softmax renormalises to 1 no matter how little mass it saw, so this
            gate scales the softmax branch back toward the share it captured — a scalar
            property of a DISTRIBUTION, hence per-head. Starts at 0.99: the softmax
            branch IS the teacher at step 0.
      LINEAR  (head_dim set)  one value per (token, head, channel): a routing decision on
            a new pathway. Low rank (bottleneck = head_dim by default).

    The init matters, especially on the linear branch: to_out_linear and every writer
    feeding the scan reach the loss ONLY through this gate, so the optimiser's cheapest
    descent direction is to close it and starve them all at once. A constant init near
    sigmoid(0.5) is the point of maximum gate mobility and invites exactly that collapse;
    `init="random"` (linear-branch gate) instead keeps torch's default init on both
    linears, matching fla's g_proj — a LIVE low-rank path, input-dependent from step 0.
    The softmax gate always uses `init="constant"`: it is the mixing gate between the
    two branches (no fla analogue) and its 0.99 is what keeps the softmax branch at the
    teacher on step 0.
    """

    def __init__(self, hidden_size, num_heads, head_dim=None, bottleneck=None,
                 init_value=0.9, init="constant"):
        super().__init__()
        self.num_heads, self.head_dim = num_heads, head_dim
        self.init_value = init_value
        out_features = num_heads * (head_dim or 1)
        self.down = None if bottleneck is None else nn.Linear(hidden_size, bottleneck,
                                                              bias=False)
        self.up = nn.Linear(bottleneck or hidden_size, out_features, bias=True)
        if init == "constant":        # gate == init_value for every token at step 0
            nn.init.zeros_(self.up.weight)
            nn.init.constant_(self.up.bias, math.log(init_value / (1.0 - init_value)))
        elif init != "random":        # torch default on both linears: live from step 0
            raise ValueError(f"OutputGate init must be 'constant' or 'random', got {init!r}")

    def forward(self, x):
        """x: [tokens, hidden] -> gate in (0, 1), [tokens, H, d] or [tokens, H, 1]."""
        gate = torch.sigmoid(self.up(x if self.down is None else self.down(x)))
        return gate.view(-1, self.num_heads, self.head_dim or 1)


# ============================================================================
# src.models.ops.rms_norm
# ============================================================================
# RMSNorm with fp32 second-moment accumulation, nn.RMSNorm-compatible.
#
# Parameterisation matches nn.RMSNorm(dim, eps): weight [dim], ones-init, so
# `linear_attention.norm.weight` loads into either implementation.
#
# Why not F.rms_norm / nn.RMSNorm directly. At the branch's shape ([F*S, H, d] with
# F*S ~ 100k, H*d = 7168, bf16):
#
#     x.pow(2).mean(dtype=fp32)   ~1e-3 relative error   small extra memory
#     x.float().pow(2).mean()     exact                  a full fp32 copy of x
#     vector_norm(dtype=fp32)^2   ~1e-7 relative error   almost no extra memory
#
# `pow(2)` runs in the INPUT dtype and rounds every square to bf16's 8 mantissa bits
# before the fp32 accumulation ever starts; promoting first is exact but materialises
# the fp32 copy. vector_norm squares and accumulates in fp32 without materialising
# anything. The weight is likewise cast DOWN, never the input up -- a bf16 x fp32
# elementwise mul would silently promote the whole tensor.

class RMSNorm(nn.Module):
    def __init__(self, dim, eps=1e-6):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim))

    def forward(self, x):
        ms = torch.linalg.vector_norm(
            x, dim=-1, keepdim=True, dtype=torch.float32).pow(2) / x.shape[-1]
        return x * torch.rsqrt(ms + self.eps).to(x.dtype) * self.weight.to(x.dtype)


# ============================================================================
# src.models.ops.temporal_conv
# ============================================================================
# One Triton kernel for the linear branch's temporal conv, its SiLU, and its L2 norm.
#
# WHY. `_tconv_activate_body` hands the chain to inductor, which is already a large win
# over eager (the five shifted multiply-adds fuse into one pass, and the SiLU and the norm
# ride along). What it cannot fix is that the shift spelling READS EACH ELEMENT FIVE
# TIMES: `xp[dt:dt+T] * w[:, dt]` is a full-tensor expression per tap, so a ~1.35 GiB
# tensor is walked five times for a 5-tap stencil whose taps overlap almost completely.
#
# The kernel below tiles over FRAMES. One program owns BLOCK_T consecutive frames, one
# spatial row and one head, and issues its five taps as five loads of the same
# [BLOCK_T, head_dim] shape offset by dt -- which overlap by BLOCK_T - 1 rows, so the
# hardware cache serves all but the first and HBM sees each frame about
# (BLOCK_T + 4) / BLOCK_T times. That is roughly a 2x speedup over the compiled shift
# chain at the real shape; BLOCK_T = 16 was the best of 8/16/32 there.
#
# WHAT IT DOES NOT DO. The 5x5 spatial half stays on cudnn: its NHWC depthwise kernel
# beats every alternative tried, including a compiled 25-tap stencil.
#
# INFERENCE ONLY, like everything else on this path: the kernel accumulates in fp32 and
# rounds once, where the eager chain rounds after every tap, so it is not bitwise (about
# one bf16 ulp relative, and closer to an fp32 reference than the chain it replaces).
#
# Triton and a CUDA tensor are REQUIRED: the inference path has no other implementation
# of this stage. The kernel's contract -- the 5-tap symmetric stencil, a power-of-two
# head_dim >= 16 (the L2 norm is a reduction inside one program's channel block),
# contiguous operands -- is checked and violated with a ValueError, not a silent
# alternative path.

BLOCK_T = 16


@triton.jit
def _tconv_act_kernel(X, W, OUT, T, S_, C_, BLOCK_T: tl.constexpr,
                      D_: tl.constexpr, L2: tl.constexpr):
    pid_t = tl.program_id(0)
    pid_s = tl.program_id(1)
    pid_h = tl.program_id(2)
    chan = pid_h * D_ + tl.arange(0, D_)
    rows = pid_t * BLOCK_T + tl.arange(0, BLOCK_T)
    valid = rows < T

    acc = tl.zeros((BLOCK_T, D_), dtype=tl.float32)
    for dt in tl.static_range(5):
        r = rows + dt - 2
        ok = valid & (r >= 0) & (r < T)                    # zero padding, both ends
        v = tl.load(X + (r[:, None] * S_ + pid_s) * C_ + chan[None, :],
                    mask=ok[:, None], other=0.0).to(tl.float32)
        wd = tl.load(W + chan * 5 + dt).to(tl.float32)
        acc += v * wd[None, :]

    y = acc * tl.sigmoid(acc)                              # SiLU
    if L2:
        inv = 1.0 / tl.sqrt(tl.maximum(tl.sum(y * y, axis=1), 1e-12))
        y = y * inv[:, None]
    tl.store(OUT + (rows[:, None] * S_ + pid_s) * C_ + chan[None, :],
             y.to(OUT.dtype.element_ty), mask=valid[:, None])


def temporal_conv_activate(x, w, kernel, pad, heads, head_dim, l2norm):
    """x [T, S, C] (CUDA, contiguous), w [C, 5] -> [T*S, heads, head_dim]."""
    if not x.is_cuda:
        raise ValueError("temporal_conv_activate is a Triton kernel; x must be on CUDA")
    if kernel != 5 or pad != 2:
        raise ValueError(f"the kernel unrolls exactly 5 symmetric taps, got kernel={kernel} "
                         f"pad={pad}")
    if head_dim & (head_dim - 1) or head_dim < 16:
        raise ValueError(f"head_dim must be a power of two >= 16 (tl.arange), got {head_dim}")
    T, S_, C_ = x.shape
    if C_ != heads * head_dim:
        raise ValueError(f"C={C_} != heads*head_dim={heads * head_dim}")
    if not (x.is_contiguous() and w.is_contiguous()):
        raise ValueError("x and w must be contiguous")
    out = torch.empty_like(x)
    _tconv_act_kernel[(triton.cdiv(T, BLOCK_T), S_, heads)](
        x, w, out, T, S_, C_, BLOCK_T=BLOCK_T, D_=head_dim, L2=l2norm,
        num_warps=4, num_stages=2)
    return out.reshape(-1, heads, head_dim)


# ============================================================================
# src.models.ops.fp8_linear
# ============================================================================
# fp8 for the DiT's big Linears. OPT-IN, NEVER A DEFAULT.
#
# WHY IT IS HERE. Once the pointwise work is fused, a block's time is dominated by GEMMs
# and attention already running near tensor-core peak; fp8 e4m3 is the remaining lever,
# roughly doubling each of the block's GEMMs.
#
# WHY IT IS NOT THE DEFAULT. fp8 does not degrade the output -- it CHANGES it. A single
# step's velocity prediction stays close to bf16's (cosine ~0.998), but a denoising
# trajectory is chaotic: perturb it early and it settles into a different mode, so the
# final latents and the decoded clip are a different (not worse) sample of the same
# prompt. fp8 IS NOT A DROP-IN: anything that depends on reproducing a previous render
# (a regression suite, a checkpoint comparison, a user re-rolling a seed) stops working.
#
# WHAT IS QUANTISED. Only Linears at or above `min_width` on BOTH sides -- the qkv
# projections, to_out, the two feed-forward GEMMs and to_out_linear. Everything narrow
# stays in bf16 on purpose: the output gates are low-rank, beta_proj is hidden -> heads,
# FrameKDAAlpha is a deliberate fp32 island, and adaln_proj reads a tiny table. None of
# them is a meaningful share of the time and all of them are places precision matters
# more than throughput.
#
# THE QUANTISER IS A TRITON KERNEL, one program per row: absmax, then the scaled cast,
# read once from HBM (the second sweep over the row comes back out of L2); the compiled
# torch spelling was several times slower than the bandwidth floor. Two callers avoid a
# quantisation altogether: `HybridAttention._qkv` quantises x once for the three
# projections (`forward_quantized`), and the inference feed-forward fuses the SwiGLU
# activation with the quantisation of its output (`swiglu_quantize`), so the bf16
# intermediate is never written.
#
# WHERE THE ERROR COMES FROM. The WEIGHTS, not the activations: rowwise activation scaling
# is no more accurate than per-tensor, while fp8 weights alone account for most of the
# error. So the lever for accuracy, if anyone wants one, is finer weight granularity
# (per-block) or keeping outlier channels in bf16 -- not a better activation scale.
# Rowwise activation scaling is used on sm90 anyway because it is free there.
#
# `skip_end_blocks` leaves the first and last N blocks in bf16; it keeps most of the
# speedup and removes a disproportionate share of the error.
#
#     from src.models.ops.fp8_linear import convert_linear_to_fp8          # infer.py
#     quantised = convert_linear_to_fp8(model)   # after any LoRA merge, before the render
#
# The swap is ONE WAY: the bf16 weight is released as each Linear is replaced, so the
# quantised model is roughly half the weight of the one it came from and there is nothing
# to put back. Rendering bf16 again means loading the model again.
#
# SM100 USES PER-TENSOR SCALES ON BOTH SIDES, and this is a dispatch fact, not a numerics
# preference. torch 2.13 routes rowwise-scaled `_scaled_mm` on sm100 to a generic CUTLASS
# kernel that is barely faster than bf16 at these shapes, while per-tensor x per-tensor
# dispatches to a cuBLAS kernel at the expected ~2x. Mixed scalar-x-vector scale
# combinations are refused by this torch build, so the fast path needs per-tensor on BOTH
# sides. The accuracy cost is negligible on the real weights, because e4m3's dynamic range
# covers their channel outliers without underflow. sm90 keeps rowwise: it is free there.
# The granularity follows the capability alone -- it is not a knob.

FP8_DTYPE = torch.float8_e4m3fn
_FP8_MAX = torch.finfo(FP8_DTYPE).max
MIN_WIDTH = 4096
SKIP_END_BLOCKS = 4


@triton.jit
def _quantize_rows_kernel(X, Y, S, K, FP8_MAX: tl.constexpr, BLOCK_K: tl.constexpr):
    row = tl.program_id(0).to(tl.int64)
    amax = tl.zeros((BLOCK_K,), dtype=tl.float32)
    for k0 in range(0, K, BLOCK_K):
        cols = k0 + tl.arange(0, BLOCK_K)
        x = tl.load(X + row * K + cols, mask=cols < K, other=0.0).to(tl.float32)
        amax = tl.maximum(amax, tl.abs(x))
    scale = tl.maximum(tl.max(amax, axis=0) / FP8_MAX, 1e-12)
    tl.store(S + row, scale)
    for k0 in range(0, K, BLOCK_K):
        cols = k0 + tl.arange(0, BLOCK_K)
        x = tl.load(X + row * K + cols, mask=cols < K, other=0.0).to(tl.float32)
        y = tl.minimum(tl.maximum(x / scale, -FP8_MAX), FP8_MAX)
        tl.store(Y + row * K + cols, y.to(Y.dtype.element_ty), mask=cols < K)


@triton.jit
def _swiglu_quantize_kernel(H, Y, S, K, FP8_MAX: tl.constexpr, BLOCK_K: tl.constexpr):
    row = tl.program_id(0).to(tl.int64)
    amax = tl.zeros((BLOCK_K,), dtype=tl.float32)
    for k0 in range(0, K, BLOCK_K):
        cols = k0 + tl.arange(0, BLOCK_K)
        a = tl.load(H + row * 2 * K + cols, mask=cols < K, other=0.0).to(tl.float32)
        g = tl.load(H + row * 2 * K + K + cols, mask=cols < K, other=0.0).to(tl.float32)
        amax = tl.maximum(amax, tl.abs(a * g * tl.sigmoid(g)))
    scale = tl.maximum(tl.max(amax, axis=0) / FP8_MAX, 1e-12)
    tl.store(S + row, scale)
    for k0 in range(0, K, BLOCK_K):
        cols = k0 + tl.arange(0, BLOCK_K)
        a = tl.load(H + row * 2 * K + cols, mask=cols < K, other=0.0).to(tl.float32)
        g = tl.load(H + row * 2 * K + K + cols, mask=cols < K, other=0.0).to(tl.float32)
        y = tl.minimum(tl.maximum(a * g * tl.sigmoid(g) / scale, -FP8_MAX), FP8_MAX)
        tl.store(Y + row * K + cols, y.to(Y.dtype.element_ty), mask=cols < K)


def _rows(x):
    if not x.is_cuda:
        raise ValueError("the fp8 quantiser is a Triton kernel; the input must be on CUDA")
    if x.dim() != 2:
        raise ValueError(f"expected [M, K], got {tuple(x.shape)}")
    return x.contiguous()


def quantize_rows(x):
    """bf16 [M, K] -> (fp8 [M, K], fp32 scale [M, 1]). One absmax per row."""
    x = _rows(x)
    M, K = x.shape
    y = torch.empty_like(x, dtype=FP8_DTYPE)
    scale = torch.empty(M, 1, device=x.device, dtype=torch.float32)
    _quantize_rows_kernel[(M,)](x, y, scale, K, FP8_MAX=_FP8_MAX, BLOCK_K=1024, num_warps=4)
    return y, scale


def swiglu_quantize(h):
    """[M, 2K] projection output -> quantize_rows(a * silu(gate)) with a, gate = h.chunk(2),
    without writing the bf16 activation."""
    h = _rows(h)
    M, K2 = h.shape
    K = K2 // 2
    y = torch.empty(M, K, device=h.device, dtype=FP8_DTYPE)
    scale = torch.empty(M, 1, device=h.device, dtype=torch.float32)
    _swiglu_quantize_kernel[(M,)](h, y, scale, K, FP8_MAX=_FP8_MAX, BLOCK_K=2048, num_warps=16)
    return y, scale


def quantize_rows_reference(x):
    """The eager spelling of `quantize_rows`, for the tests."""
    scale = (x.float().abs().amax(dim=1, keepdim=True) / _FP8_MAX).clamp_min(1e-12)
    return (x.float() / scale).to(FP8_DTYPE), scale


_PER_TENSOR = None


def per_tensor_gemm():
    """sm100 uses per-tensor scales (see the header); sm90 keeps rowwise."""
    global _PER_TENSOR
    if _PER_TENSOR is None:
        _PER_TENSOR = (torch.cuda.is_available()
                       and torch.cuda.get_device_capability(0)[0] >= 10)
    return _PER_TENSOR


@triton.jit
def _absmax_kernel(X, OUT, N, BLOCK: tl.constexpr):
    """Partial absmax + one atomic per program: a full reduction in ONE read pass,
    where eager `x.abs().amax()` materialises the abs (a full-size write at the qkv
    shape) before it reduces."""
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    x = tl.load(X + offs, mask=offs < N, other=0.0).to(tl.float32)
    tl.atomic_max(OUT, tl.max(tl.abs(x), axis=0))


@triton.jit
def _cast_scaled_kernel(X, Y, S, N, FP8_MAX: tl.constexpr, BLOCK: tl.constexpr):
    pid = tl.program_id(0).to(tl.int64)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    scale = tl.load(S)
    x = tl.load(X + offs, mask=mask, other=0.0).to(tl.float32)
    y = tl.minimum(tl.maximum(x / scale, -FP8_MAX), FP8_MAX)
    tl.store(Y + offs, y.to(Y.dtype.element_ty), mask=mask)


@triton.jit
def _swiglu_rowmax_kernel(H, Y, RM, K, BLOCK_K: tl.constexpr):
    """a * silu(gate) per row into bf16 Y, plus the row's absmax -- the per-tensor
    spelling of `_swiglu_quantize_kernel`, split so the global scale can be taken
    before the cast."""
    row = tl.program_id(0).to(tl.int64)
    amax = tl.zeros((BLOCK_K,), dtype=tl.float32)
    for k0 in range(0, K, BLOCK_K):
        cols = k0 + tl.arange(0, BLOCK_K)
        mask = cols < K
        a = tl.load(H + row * 2 * K + cols, mask=mask, other=0.0).to(tl.float32)
        g = tl.load(H + row * 2 * K + K + cols, mask=mask, other=0.0).to(tl.float32)
        act = (a * g * tl.sigmoid(g)).to(Y.dtype.element_ty)
        # amax of the ROUNDED value: the bf16 intermediate is the tensor being
        # quantised, so its own absmax is the scale.
        amax = tl.maximum(amax, tl.abs(act.to(tl.float32)))
        tl.store(Y + row * K + cols, act, mask=mask)
    tl.store(RM + row, tl.max(amax, axis=0))


def quantize_tensor(x):
    """bf16 [M, K] -> (fp8 [M, K], fp32 scale [1, 1]). One absmax for the whole tensor;
    the scale never leaves the device (no sync)."""
    x = _rows(x)
    n = x.numel()
    amax = torch.zeros(1, device=x.device, dtype=torch.float32)
    _absmax_kernel[(triton.cdiv(n, 8192),)](x.view(-1), amax, n, BLOCK=8192,
                                            num_warps=8)
    scale = (amax / _FP8_MAX).clamp_min(1e-12).reshape(1, 1)
    y = torch.empty_like(x, dtype=FP8_DTYPE)
    _cast_scaled_kernel[(triton.cdiv(n, 8192),)](x.view(-1), y.view(-1), scale, n,
                                                 FP8_MAX=_FP8_MAX, BLOCK=8192,
                                                 num_warps=8)
    return y, scale


def quantize_tensor_reference(x):
    """The eager spelling of `quantize_tensor`, for the tests."""
    scale = (x.float().abs().amax() / _FP8_MAX).clamp_min(1e-12).reshape(1, 1)
    return (x.float() / scale).to(FP8_DTYPE), scale


def swiglu_quantize_tensor(h):
    """[M, 2K] projection output -> per-tensor quantised a * silu(gate). One extra
    bf16 write against the fused rowwise kernel; the fast GEMM it unlocks on sm100
    repays it many times over."""
    h = _rows(h)
    M, K2 = h.shape
    K = K2 // 2
    act = torch.empty(M, K, device=h.device, dtype=h.dtype)
    rowmax = torch.empty(M, device=h.device, dtype=torch.float32)
    _swiglu_rowmax_kernel[(M,)](h, act, rowmax, K, BLOCK_K=2048, num_warps=16)
    scale = (rowmax.amax() / _FP8_MAX).clamp_min(1e-12).reshape(1, 1)
    y = torch.empty_like(act, dtype=FP8_DTYPE)
    n = act.numel()
    _cast_scaled_kernel[(triton.cdiv(n, 8192),)](act.view(-1), y.view(-1), scale, n,
                                                 FP8_MAX=_FP8_MAX, BLOCK=8192,
                                                 num_warps=8)
    return y, scale


def quantize_activation(x):
    """What the GEMM callers use: the scale granularity the current card's fast
    `_scaled_mm` path accepts."""
    return quantize_tensor(x) if per_tensor_gemm() else quantize_rows(x)


def swiglu_quantize_activation(h):
    return swiglu_quantize_tensor(h) if per_tensor_gemm() else swiglu_quantize(h)


class Fp8Linear(nn.Module):
    """A bias-optional Linear whose GEMM runs in fp8 e4m3.

    The weight is quantised ONCE, per output channel, at construction; the activation is
    quantised per row on every call, or by the caller (`forward_quantized`) when one
    activation feeds several of these. Only the fp8 copy and the bias are kept -- the
    bf16 weight goes as soon as the caller drops the Linear it came from.
    """

    def __init__(self, linear: nn.Linear):
        super().__init__()
        weight = linear.weight
        if per_tensor_gemm():
            # sm100: both scales must be scalar for the fast cuBLAS path; on the real
            # weights this costs nothing measurable over per-channel (see the header).
            scale = (weight.abs().amax().float() / _FP8_MAX).clamp_min(1e-12)
            self.register_buffer("weight_fp8",
                                 (weight / scale.to(weight.dtype)).to(FP8_DTYPE))
            self.register_buffer("weight_scale", scale.reshape(1, 1).contiguous())
        else:
            scale = (weight.abs().amax(dim=1, keepdim=True).float()
                     / _FP8_MAX).clamp_min(1e-12)
            self.register_buffer("weight_fp8",
                                 (weight / scale.to(weight.dtype)).to(FP8_DTYPE))
            self.register_buffer("weight_scale", scale.reshape(1, -1).contiguous())
        self.register_parameter("bias", linear.bias)

    def forward_quantized(self, x_fp8, x_scale, out_dtype=torch.bfloat16):
        """[M, K] fp8 rows and their scales ([M, 1] rowwise / [1, 1] per-tensor) -> [M, N]."""
        out = torch._scaled_mm(x_fp8, self.weight_fp8.t(),
                               scale_a=x_scale, scale_b=self.weight_scale,
                               out_dtype=out_dtype, use_fast_accum=True)
        if self.bias is not None:
            out = out + self.bias
        return out

    def forward(self, x):
        shape = x.shape
        rows = x.reshape(-1, shape[-1])
        out = self.forward_quantized(*quantize_activation(rows), out_dtype=rows.dtype)
        return out.reshape(*shape[:-1], -1)


def _blocks_to_skip(model, skip_end_blocks):
    """ids of every module inside the first and last N transformer blocks."""
    blocks = getattr(model, "transformer_blocks", None)
    if not blocks or skip_end_blocks <= 0:
        return set()
    keep = set()
    for index, block in enumerate(blocks):
        if index < skip_end_blocks or index >= len(blocks) - skip_end_blocks:
            keep.update(id(m) for m in block.modules())
    return keep


def convert_linear_to_fp8(model, min_width=MIN_WIDTH, skip_end_blocks=SKIP_END_BLOCKS):
    """Swap the wide Linears for fp8 ones, in place. Returns how many were swapped.

    Call it AFTER any LoRA merge -- the merger writes into `Linear.weight`, and this
    reads that weight once to build the fp8 copy. Converting first would quantise the
    unmerged weights and then silently ignore the merge.

    One Linear at a time, and the bf16 one is unreferenced the moment its parent is
    repointed: peak memory is the model plus a single fp8 weight, and it falls from
    there. There is no way back -- see the header.
    """
    skip = _blocks_to_skip(model, skip_end_blocks)
    swapped = 0
    for parent in list(model.modules()):
        for name, child in list(parent.named_children()):
            if not isinstance(child, nn.Linear):
                continue
            if child.in_features < min_width or child.out_features < min_width:
                continue
            if id(child) in skip:
                continue
            setattr(parent, name, Fp8Linear(child).to(child.weight.device))
            swapped += 1
    return swapped


