# flex_attention with the FLASH/CuteDSL backend, the BlockMask builder and
# its caches. The FLASH variant is a static compile, which is why mask geometry is one
# process, one geometry (see infer entrypoint).

_FLEX_CACHE = {}                 # the compiled flex_attention, one entry, never evicted

# BlockMasks, bounded. Each one is ~10 MiB of GPU tensors at H3 scale, the same
# regardless of radius — kv_indices is allocated at max width. The key includes seq_len,
# which varies with the caption, AND the window bounds: unbounded, 100 distinct prompt
# lengths would park ~1 GiB on the GPU permanently. A run trains one fixed radius, so
# the working set is just the seq_len buckets the dataset spans; 64 caps it at ~650 MiB.
_MASK_CACHE = collections.OrderedDict()


def _flex_attention_fn(inference=False):
    """torch.compile'd flex_attention. Two variants, and the difference is 1.6x.

    TRAINING (inference=False) — dynamic=True, Triton, ONE graph for every sequence
    length. dynamic=False is a landmine here. The packed length varies with the caption,
    so a static compile makes a fresh cache entry per length; torch._dynamo's
    recompile_limit is 8, and on the 9th distinct length it stops compiling and runs
    flex_attention EAGER, which materialises the full score matrix (56 x ~104k^2 x 2 B).
    A short benchmark cannot catch this — 3-4 steps see at most 4 distinct lengths.

    `fail_on_recompile_limit_hit` matters most, because the degradation is silent by
    construction: dynamo logs a warning and keeps running, and what surfaces is an OOM
    with no obvious connection to shapes. As an exception, an unanticipated shape stops
    the run instead of quietly falling off the fast path.

    INFERENCE (inference=True) — dynamic=False and CuteDSL/FlashAttention-4. At the
    real shape and mask this is ~1.6x faster per layer than the Triton path: the
    block-sparse FLASH kernel realises the sparsity almost perfectly, so its throughput
    approaches the dense FA4 kernel's.

    Why the two cannot be one. FLASH refuses a BlockMask under a dynamic compile:

        NYI: score_mod or mask_mod captures a dynamic scalar (SymInt/SymFloat). The
        FLASH backend cannot inline symbolic values into the CuteDSL template.

    and the symbols are inside the BlockMask itself (its Q_LEN, KV_LEN, block sizes), so
    rewriting our mask_mod's captures as device tensors does not help. dynamic=False is
    the only door, and it is a door only inference can walk through: one render process
    renders one prompt, so seq_len is fixed for its whole life, while training brings a
    new caption every batch. The restriction is narrower than "FLASH needs static
    shapes" — the DENSE FA4 teacher runs under a dynamic compile, because with no mask
    there is no template to inline into.

    The static variant keeps the recompile limit that guards the dynamic one, so a
    process that does see 9 distinct lengths raises rather than degrading.
    """
    key = "infer" if inference else "train"
    if key not in _FLEX_CACHE:
        torch._dynamo.config.fail_on_recompile_limit_hit = True

        # ...and raise the limit itself, which is a DIFFERENT knob and does not weaken
        # the one above. `recompile_limit` is per code object and defaults to 8; the
        # inference path compiles a dozen small helpers (the epilogues, the feature
        # kernels, the gather) whose bodies each specialise on a couple of flags, and a
        # process that exercises more than one configuration -- a test sweep, an
        # ablation driver -- exhausts 8 on a helper that has nothing to do with
        # attention. What protects the window kernel is the HARD FAILURE, not the
        # number: at 8 or at 32, an unanticipated sequence length stops the run instead
        # of silently falling back to eager flex_attention. 32 only buys tolerance for
        # more distinct caption lengths before that happens.
        torch._dynamo.config.recompile_limit = max(
            32, torch._dynamo.config.recompile_limit)
        if inference:
            _FLEX_CACHE[key] = torch.compile(
                functools.partial(flex_attention, kernel_options={"BACKEND": "FLASH"}),
                dynamic=False)
        else:
            _FLEX_CACHE[key] = torch.compile(flex_attention, dynamic=True)
    return _FLEX_CACHE[key]


def build_window_block_mask(layout: SequenceLayout, bounds, device, block_size=None,
                            anchor_frames="none"):
    """BlockMask for: video<->video pairs restricted to the per-frame window, every pair
    involving a global (text/audio) token dense. Cached per (layout, bounds, anchors).

    anchor_frames: how frames 0 and F-1 are dense -- "columns" (every video query sees
    all of both frames), "rows" (those two frames' queries see the whole sequence),
    "both", or "none". Under "both" the linear branch drops the two frames from its
    input (BidirectionalLinearBranch.forward's skip_ends) and softmax and branch stay an
    exact partition. The two anchor frames add a few points of mask density."""
    if anchor_frames not in ANCHOR_FRAME_MODES:
        raise ValueError(f"anchor_frames={anchor_frames!r}; expected one of {ANCHOR_FRAME_MODES}")
    if block_size is None:
        # FA4's CuteDSL block-sparse template is tile-shaped per arch. SM90: both sides
        # 128 ("sparse_block_size[1] must be a multiple of tile_n=128"). SM100: the
        # tiles are ASYMMETRIC -- a 128 mask is refused on the Q side ("block size 128,
        # which must be a multiple of 256") and a 256 mask on the KV side
        # ("sparse_block_size[1]=128 to match tile_n") -- so the mask must be built at
        # (Q=256, KV=128). The coarser Q granularity rounds the window up a little, but
        # that tax is far below the Triton fallback the process is otherwise latched
        # into.
        block_size = 128
        resolved = torch.device(device) if not isinstance(device, torch.device) else device
        if resolved.type == "cuda" and torch.cuda.get_device_capability(resolved)[0] >= 10:
            block_size = (256, 128)
    key = (layout.seq_len, layout.video_start, layout.num_frames,
           layout.tokens_per_frame, tuple(bounds), block_size, str(device),
           anchor_frames)
    if key in _MASK_CACHE:
        _MASK_CACHE.move_to_end(key)
        return _MASK_CACHE[key]

    video_start, video_end = layout.video_start, layout.video_end
    tokens_per_frame, num_frames = layout.tokens_per_frame, layout.num_frames
    window_lo = torch.tensor([lo for lo, _ in bounds], device=device)
    window_hi = torch.tensor([hi for _, hi in bounds], device=device)

    def mask_mod(batch, head, q_idx, kv_idx):
        query_is_video = (q_idx >= video_start) & (q_idx < video_end)
        key_is_video = (kv_idx >= video_start) & (kv_idx < video_end)

        # frame index of each row; the query side is clamped because mask_mod is also
        # evaluated on global rows, where the division would run out of range
        query_frame = torch.clamp(
            torch.div(q_idx - video_start, tokens_per_frame, rounding_mode="floor"),
            0, num_frames - 1)
        key_frame = torch.div(kv_idx - video_start, tokens_per_frame,
                              rounding_mode="floor")
        inside_window = ((key_frame >= window_lo[query_frame])
                         & (key_frame <= window_hi[query_frame]))
        is_anchor = lambda f: (f == 0) | (f == num_frames - 1)
        if anchor_frames in ("columns", "both"):
            inside_window = inside_window | is_anchor(key_frame)        # everyone sees them
        if anchor_frames in ("rows", "both"):
            inside_window = inside_window | is_anchor(query_frame)      # they see everyone
        # keep the pair unless BOTH sides are video and the key falls outside the window
        return (~(query_is_video & key_is_video)) | inside_window

    mask = create_block_mask(mask_mod, B=None, H=None, Q_LEN=layout.seq_len,
                             KV_LEN=layout.seq_len, device=device,
                             BLOCK_SIZE=block_size, _compile=True)
    _MASK_CACHE[key] = mask
    while len(_MASK_CACHE) > MAX_CACHED_MASKS:
        _MASK_CACHE.popitem(last=False)
    return mask


def flash_backend_available(device):
    """Whether the FLASH (FA4 CuTe) flex backend is the right kernel on this card,
    decided once per process by the card alone. FA4 implements block sparsity on sm90
    and sm100 only: its sm8x kernel accepts the block tensors and never reads them, so
    every query would visit every KV block -- correct output at DENSE cost, and no error
    to catch; sm120 asserts. Those cards run the Triton kernel, whose BlockMask skipping
    is generic. On the cards that have it flash-attn-4 is required: its absence raises
    from the first FLASH call."""
    if "flash_available" not in _FLEX_CACHE:
        _FLEX_CACHE["flash_available"] = has_fa4_kernels(device)
    return _FLEX_CACHE["flash_available"]


_FLEX_INFER_WARNED = False


def _warn_inference_flex():
    """One warning per process when INFERENCE lands on the flex/BlockMask window on
    sm100 -- not the preferred kernel there. Names whichever piece is missing: the
    decomposition (faster than even CLC-scheduled flex), FA_CLC=1 (the static schedule
    is slower), and the flash-attn gate patch (without it FA_CLC=1 is silently stripped
    for block-sparse calls). sm90 stays quiet: flex IS the right kernel there. With
    everything configured correctly there is no warning at all."""
    global _FLEX_INFER_WARNED
    if _FLEX_INFER_WARNED:
        return
    _FLEX_INFER_WARNED = True
    if not torch.cuda.is_available() or torch.cuda.get_device_capability(0)[0] < 10:
        return
    msgs = ["kernels.softmax_backend is flex here; auto picks the decomposition, which "
            "runs this window faster than even CLC-scheduled flex"]
    if os.environ.get("FA_CLC") != "1":
        msgs.append("FA_CLC=1 is not set -- flex is running the STATIC block-sparse "
                    "schedule, which is noticeably slower on sm100")
    else:
        import flash_attn.cute.interface as _fa_iface
        with open(_fa_iface.__file__) as fh:
            src_text = fh.read()
        i = src_text.find("is_dense_noncausal =")
        # the patched assignment spans two physical lines, so search a window
        # after the assignment rather than line-by-line
        patched = i < 0 or "use_block_sparsity" in src_text[i:i + 220]
        if not patched:
            msgs.append("FA_CLC=1 is set but the installed flash-attn STRIPS CLC for "
                        "block-sparse calls -- patch flash_attn/cute/interface.py so "
                        "is_dense_noncausal also excludes use_block_sparsity")
    if msgs:
        warnings.warn(
            "sm100 INFERENCE is on the flex/BlockMask window softmax: "
            + "; ".join(msgs), RuntimeWarning, stacklevel=3)


def collect_after_first_flash():
    """One gc.collect() after the FIRST FLASH window call has RETURNED to HybridAttention,
    once per process. The call that compiles the FLASH variant leaves its q, k and v in a
    reference cycle of torch.fx nodes from the trace: after the caller drops them they
    stay allocated until the cyclic collector happens to run, which at H3 scale is 4.2 GiB
    (three [T, H, d] bf16 tensors at 345 frames) on the peak of every later layer --
    23.1 GB instead of 18.9 per transformer call, streamed. Collected from the caller,
    not inside window_softmax_flex: a collection inside that frame, right after the
    compiled call, does not free it (measured); one after the frame has returned does."""
    if _FLEX_CACHE.get("infer") is None or _FLEX_CACHE.get("collected"):
        return
    gc.collect()
    _FLEX_CACHE["collected"] = True


def window_softmax_flex(query, key, value, block_mask, scale, head_chunk=None,
                         inference=False):
    """query/key/value: [total, H, d] -> [total, H, d] via block-sparse FlexAttention.

    NO REPACK. flex wants [B, H, T, d] and both its backends accept it as a strided
    VIEW of the [T, H, d] the projections produce (d contiguous, T stride H*d), at the
    same speed and with bitwise-identical output. That removes three ~1.4 GiB
    transposing copies per layer (q, k, v) plus one on the way out: the output inherits
    q's strides, so `.transpose` back to [T, H, d] is a view and the gate/to_out
    downstream read it contiguously.

    Heads normally go in ONE call. They are only split when a single call would index
    past int32: inductor's Triton templates address the q/k/v tensors with 32-bit
    offsets, so a call is safe while total * head_dim * heads_per_call <= 2^31 - 1.
    That is a computed bound, not a probe — probing group sizes both recompiles
    flex_attention per size (straight into the recompile limit) and is strictly slower.
    At H3 scale (~104k x 128 x 56 = 7.5e8) the limit is far away, so one call.
    `head_chunk` overrides it for the one case the bound cannot see — running out of
    memory on a smaller card.

    `inference` selects the FLASH/static variant (see _flex_attention_fn) on the cards
    that have it (`flash_backend_available`), the Triton kernel elsewhere. Nothing is
    caught: a missing flash-attn-4, a 9th distinct sequence length or a template that
    does not build raise, naming the cause.
    """
    if inference:
        _warn_inference_flex()
    num_heads = value.shape[1]
    if head_chunk is None:
        budget = (2 ** 31 - 1) // (value.shape[0] * value.shape[2])
        head_chunk = max(1, min(num_heads, budget))
    flex = _flex_attention_fn(inference=inference and flash_backend_available(query.device))

    outputs = []
    for first_head in range(0, num_heads, head_chunk):
        heads = slice(first_head, min(first_head + head_chunk, num_heads))
        q_g, k_g, v_g = (t[:, heads].unsqueeze(0).transpose(1, 2)      # [1, Hc, T, d] view
                         for t in (query, key, value))
        out_g = flex(q_g, k_g, v_g, block_mask=block_mask, scale=scale)
        outputs.append(out_g.squeeze(0).transpose(0, 1))                 # [T, Hc, d]

    # the common case is one group, and then this is a view, not a copy
    return outputs[0] if len(outputs) == 1 else torch.cat(outputs, dim=1)


# ============================================================================
# src.models.softmax_attention.decomposed
# ============================================================================
# The window softmax as a union of DENSE attentions -- no BlockMask, no sparse kernel.
#
# The c1 mask is not arbitrary sparsity: every kept pair lies in one of a few dense
# rectangles. Split the QUERY rows into groups whose kept KV set is identical, and each
# group is a plain dense attention:
#
#   dense-q   global (text/audio) rows, plus anchor-frame queries under rows/both ->
#             one flash_attn_func call against the FULL kv (no copy).
#   windows   remaining frames grouped by identical window bounds (== chunks) -> ONE
#             flash_attn_varlen_func call over per-group gathered kv
#             [globals + window frames + anchor frames].
#
# Same math as the masked kernel -- each query's softmax spans exactly its kept set in
# one pass -- so outputs differ from flex by bf16 reduction order only (a few 1e-3
# relative, the same distance two flex backends show against each other). On sm100 the
# dense calls are markedly faster than the block-sparse flex kernel at this mask density;
# on sm90 the two run at the same speed.
#
# Inference-only (config kernels.softmax_backend = decomposed, and what auto resolves to on
# every CUDA device; hybrid_transform.set_softmax_backend writes the choice onto every
# hybrid layer): training keeps the flex path. No fallback: a failure here raises rather
# than silently downgrading to a slower kernel.
#
# The window leg's varlen kernel is chosen once per process by the card (`varlen_kernel`):
# FA4's CuTe kernel on sm90, sm100 and sm110, the cards FA4 has kernels for; torch's own
# `varlen_attn` (its flash kernels, the FA2 lineage, sm80 and up) elsewhere, i.e. on sm8x
# and on consumer Blackwell (sm120). Nothing is caught: a missing kernel raises with the
# install to fix. The dense leg is torch SDPA: cuDNN on the FA4 cards, where it beats FA4
# at this shape, SDPA's own choice elsewhere.

_PLAN_CACHE = {}
_KERNEL_CACHE = {}
MAX_CACHED_PLANS = 4
SOFTMAX_BACKENDS = ("auto", "flex", "decomposed", "ref")


def _fa4_varlen():
    from flash_attn.cute.interface import flash_attn_varlen_func

    def fa4(q, k, v, cu_q, cu_k, max_q, max_k, scale):
        out = flash_attn_varlen_func(q, k, v, cu_seqlens_q=cu_q, cu_seqlens_k=cu_k,
                                     max_seqlen_q=max_q, max_seqlen_k=max_k,
                                     softmax_scale=scale)
        return out[0] if isinstance(out, tuple) else out

    fa4.name = "fa4"
    return fa4


def _torch_varlen():
    from torch.nn.attention.varlen import varlen_attn

    def torch_varlen(q, k, v, cu_q, cu_k, max_q, max_k, scale):
        return varlen_attn(q, k, v, cu_q, cu_k, max_q, max_k, scale=scale)

    torch_varlen.name = "torch"
    return torch_varlen


def varlen_kernel():
    """The varlen kernel the window leg runs on, resolved once per process: FA4's on the
    cards it has kernels for, torch's own elsewhere (see the header). An ImportError
    here is the install to fix: flash-attn-4 on those cards, torch >= 2.13 elsewhere."""
    if "varlen" not in _KERNEL_CACHE:
        _KERNEL_CACHE["varlen"] = _fa4_varlen() if has_fa4_kernels() else _torch_varlen()
    return _KERNEL_CACHE["varlen"]


def _dense_backends():
    """cuDNN SDPA on the FA4 cards, where it is faster than FA4 at the dense leg's shape;
    elsewhere SDPA picks among its own kernels."""
    if has_fa4_kernels():
        return [SDPBackend.CUDNN_ATTENTION]
    return [SDPBackend.FLASH_ATTENTION, SDPBackend.EFFICIENT_ATTENTION,
            SDPBackend.CUDNN_ATTENTION]      # no MATH: it materialises the full score matrix


def resolve_softmax_backend(backend: str) -> str:
    """Config ``kernels.softmax_backend`` -> the implementation that will run. ``auto``
    is ``decomposed`` on every CUDA device: on sm100 it is the faster kernel, on sm90 it
    matches flex at the production width and is the same distance from the fp32
    reference (bf16 reduction order). So inference runs ONE window kernel on both
    architectures, the exact window with no mask machinery; flex stays what training
    uses. A CUDA device with no varlen kernel raises here, naming the install.
    ``flex`` / ``decomposed`` force either kernel; ``ref`` is the eager reference for
    parity/debug."""
    if backend not in SOFTMAX_BACKENDS:
        raise ValueError(f"kernels.softmax_backend={backend!r}; expected one of "
                         f"{SOFTMAX_BACKENDS}")
    if backend == "auto":
        if not torch.cuda.is_available():
            return "flex"
        backend = "decomposed"
    if backend == "decomposed":
        varlen_kernel()                   # raise now, with the install named, not mid-render
    return backend


class _Plan:
    __slots__ = ("dense_q", "win_q", "kv_gather", "cu_q", "cu_k", "max_q", "max_k",
                 "has_windows")

    def __init__(self, layout: SequenceLayout, bounds, anchor_frames, device):
        S = layout.seq_len
        F, TPF = layout.num_frames, layout.tokens_per_frame
        vs, ve = layout.video_start, layout.video_end
        anchor_set = {0, F - 1} if anchor_frames in ("columns", "rows", "both") else set()
        dense_row_frames = anchor_set if anchor_frames in ("rows", "both") else set()
        dense_col_frames = anchor_set if anchor_frames in ("columns", "both") else set()

        def frame_rows(f):
            return (vs + f * TPF, vs + (f + 1) * TPF)

        global_ranges = [r for r in ((0, vs), (ve, S)) if r[0] < r[1]]

        def merge(ranges):
            out = []
            for a, b in sorted(ranges):
                if out and out[-1][1] >= a:
                    out[-1] = (out[-1][0], max(out[-1][1], b))
                else:
                    out.append((a, b))
            return out

        def cat_ranges(ranges):
            return torch.cat([torch.arange(a, b, device=device) for a, b in ranges])

        # dense-q rows: globals + anchor-row frames
        dense_ranges = merge(global_ranges + [frame_rows(f) for f in sorted(dense_row_frames)])
        self.dense_q = cat_ranges(dense_ranges) if dense_ranges else torch.empty(
            0, dtype=torch.long, device=device)

        # window groups: consecutive frames sharing identical bounds (== chunks)
        groups = []
        for f in range(F):
            if f in dense_row_frames:
                continue
            if groups and bounds[groups[-1][-1]] == bounds[f] and groups[-1][-1] == f - 1:
                groups[-1].append(f)
            else:
                groups.append([f])

        q_idx, kv_idx, q_lens, k_lens = [], [], [], []
        for frames in groups:
            lo, hi = bounds[frames[0]]
            kv_frames = sorted(set(range(max(lo, 0), min(hi + 1, F))) | dense_col_frames)
            q_r = merge([frame_rows(f) for f in frames])
            kv_r = merge(global_ranges + [frame_rows(f) for f in kv_frames])
            qi, ki = cat_ranges(q_r), cat_ranges(kv_r)
            q_idx.append(qi); kv_idx.append(ki)
            q_lens.append(len(qi)); k_lens.append(len(ki))

        self.has_windows = bool(groups)
        if self.has_windows:
            self.win_q = torch.cat(q_idx)
            self.kv_gather = torch.cat(kv_idx)
            zero = torch.zeros(1, dtype=torch.long)
            self.cu_q = torch.cat([zero, torch.tensor(q_lens).cumsum(0)]).to(
                device, torch.int32)
            self.cu_k = torch.cat([zero, torch.tensor(k_lens).cumsum(0)]).to(
                device, torch.int32)
            self.max_q, self.max_k = max(q_lens), max(k_lens)
        else:
            self.win_q = torch.empty(0, dtype=torch.long, device=device)

        order = torch.cat([self.dense_q, self.win_q])
        if len(order) != S:
            raise ValueError(f"decomposition covers {len(order)} of {S} rows")


def _plan(layout, bounds, anchor_frames, device):
    key = (layout.seq_len, layout.video_start, layout.num_frames,
           layout.tokens_per_frame, tuple(bounds), anchor_frames, str(device))
    if key not in _PLAN_CACHE:
        _PLAN_CACHE[key] = _Plan(layout, bounds, anchor_frames, device)
        while len(_PLAN_CACHE) > MAX_CACHED_PLANS:
            _PLAN_CACHE.pop(next(iter(_PLAN_CACHE)))
    return _PLAN_CACHE[key]


def window_softmax_decomposed(query, key, value, layout, bounds, scale,
                              anchor_frames="none"):
    """[T, H, d] q/k/v -> [T, H, d], exactly the window+anchors+globals mask, as
    dense calls scatter-written straight into a contiguous output (no cat +
    inverse-permute pass; the row sets are disjoint and cover [0, T)). Strided
    q is fine (indexing copies); strided k/v are copied contiguous up front --
    FA4 mis-addresses slice-strided operands on sm100, and gathers from a strided
    source are slower anyway, so one copy serves both legs. The dense-q leg runs on
    SDPA (cuDNN on sm90 and up, faster than FA4 at this shape); the window leg on
    `varlen_kernel()`."""
    varlen = varlen_kernel()

    plan = _plan(layout, bounds, anchor_frames, query.device)
    if not key.is_contiguous():
        key = key.contiguous()
    if not value.is_contiguous():
        value = value.contiguous()
    out = torch.empty(query.shape, dtype=query.dtype, device=query.device)
    if len(plan.dense_q):
        qd = query[plan.dense_q]
        with sdpa_kernel(_dense_backends()):
            od = scaled_dot_product_attention(
                qd.transpose(0, 1).unsqueeze(0),
                key.transpose(0, 1).unsqueeze(0),
                value.transpose(0, 1).unsqueeze(0), scale=scale)
        out[plan.dense_q] = od[0].transpose(0, 1)
    if plan.has_windows:
        kw = key[plan.kv_gather]
        vw = value[plan.kv_gather]
        out[plan.win_q] = varlen(query[plan.win_q], kw, vw, plan.cu_q, plan.cu_k,
                                 plan.max_q, plan.max_k, scale)
    return out


# ============================================================================
# src.models.softmax_attention.dense_processor
# ============================================================================
# Dense (full-sequence) softmax attention for the STOCK H3 attention module, on
# FlexAttention's FlashAttention-4 backend. This is the teacher trunk's kernel in Stage A1
# -- a model kernel, not trainer machinery.

class FlexFA4Processor:
    """MiniMaxH3AttnProcessor with the attention call swapped for FlexAttention's
    FlashAttention-4 (CuTeDSL) backend, which is faster than cuDNN SDPA at the H3 shape
    for both forward and forward+backward. Everything around the call (qkv projections,
    per-head norms, rotary) mirrors the stock processor, so LoRA-wrapped projections
    apply as-is.
    """

    _flex_flash = None  # compiled once per process, shared by every block

    def __call__(self, attn, hidden_states, rotary_emb=None, attention_mask=None):
        if attention_mask is not None:
            raise ValueError("H3 packs one request per document; no attention mask expected.")
        if FlexFA4Processor._flex_flash is None:
            FlexFA4Processor._flex_flash = torch.compile(
                partial(flex_attention, kernel_options={"BACKEND": "FLASH"})
            )

        query = attn.to_q(hidden_states).unflatten(-1, (attn.heads, -1))
        key = attn.to_k(hidden_states).unflatten(-1, (attn.heads, -1))
        value = attn.to_v(hidden_states).unflatten(-1, (attn.heads, -1))
        query = attn.norm_q(query)
        key = attn.norm_k(key)
        if rotary_emb is not None:
            query = _apply_rotary_emb(query, *rotary_emb)
            key = _apply_rotary_emb(key, *rotary_emb)

        # flex takes (B, H, S, D); the processor layout is (B, S, H, D).
        out = FlexFA4Processor._flex_flash(
            query.permute(0, 2, 1, 3), key.permute(0, 2, 1, 3), value.permute(0, 2, 1, 3)
        )
        out = out.permute(0, 2, 1, 3).flatten(2, 3).type_as(query)
        out = attn.to_out[0](out)
        return attn.to_out[1](out)


# ============================================================================
# src.models.hybrid_attention
# ============================================================================
# HybridAttention: the orchestrator and nothing else.
#
# Drop-in replacement for the diffusers MiniMaxH3Attention inside a DiT block. It owns
# the shared QKV, calls the softmax window and the linear branch, and fuses:
#
#     softmax_output = orig.to_out( softmax_gate(x) * window_softmax(q, k, v) )
#     linear_readout = output_gate(x) * RMSNorm( linear_attention(q_raw, k_raw, v_raw) )
#     output         = softmax_output + to_out_linear(linear_readout)   # video rows only
#
# to_out_linear takes nn.Linear's default init. Init-only: any checkpoint overwrites this
# weight on load.

class HybridAttention(nn.Module):
    """Drop-in replacement for the diffusers `MiniMaxH3Attention` inside a DiT block:
    same forward signature `(hidden_states, rotary_emb, attention_mask)`, same output
    contract (pre-residual attention output, batch-first). Batch must be 1 — H3 packs
    one request per document. Set `.layout` (SequenceLayout) before each forward and
    `.radius` to choose the frame window; the operating range is r <= 5.
    `radius >= num_frames-1` (or layout=None) makes the softmax branch equal to full
    attention.

    `.teacher_mode = True` makes forward a pure pass-through to the original attention —
    Stage A runs the trunk that way (teacher trajectory, no_grad) and computes the
    student output in a forward hook, keeping alignment a training strategy rather than
    a property of the module (see train_stage_a1.py's AlignHook)."""

    def __init__(self, orig_attn, hidden_size, delta_rule="sana_scaled", radius=4,
                 chunk=0, enable_softmax_gate=True, linear_head_dim=None,
                 softmax_impl="flex", anchor_frames="none", enable_text_state=False,
                 bridge="alpha", a_fp32=True, short_conv=()):
        """Keyword names mirror the ModelSpec transform config one-to-one
        (`softmax_attention.{radius,chunk}`, `anchor_frames`,
        `linear_attention.{delta_rule,linear_head_dim,bridge,a_fp32,enable_text_state}`,
        `linear_attention.short_conv.targets` as `short_conv`, `enable_softmax_gate`);
        `softmax_impl` is the one runtime knob ("flex" | "decomposed" | "ref", set by
        hybrid_transform.set_softmax_backend) and never enters a spec.

        anchor_frames: how frames 0 and F-1 sit in the softmax mask -- "columns" (every
        video query sees all of both frames), "rows" (those two frames' queries see the
        whole sequence), "both", or "none". A cross-branch fact: under "both" the two
        frames are exact softmax in both directions, so the linear branch drops them from
        its input (skip_ends) and the softmax/linear partition stays exact. Under
        "columns" or "rows" alone the partition would not be exact, so the branch keeps
        covering them."""
        super().__init__()
        self.orig = orig_attn                                    # original weights, reused
        self.num_heads = orig_attn.heads
        self.head_dim = orig_attn.head_dim
        self.radius = radius
        self.chunk = chunk           # 0 = frame window ("r<n>"); K = K-frame chunks ("c<n>")
        self.softmax_impl = softmax_impl                         # "flex" | "decomposed" | "ref"

        if anchor_frames not in ANCHOR_FRAME_MODES:
            raise ValueError(f"anchor_frames={anchor_frames!r}; expected one of "
                             f"{ANCHOR_FRAME_MODES}")
        self.anchor_frames = anchor_frames

        # Seed both linear-branch scans with the prompt (see BidirectionalLinearBranch.
        # forward). Needs a layout that carries the text rows — layout_from_indices
        # must have been given text_indices.
        self.enable_text_state = enable_text_state
        self.linear_attention_enabled = True    # False = window-only ablation (pure sparse attention)
        self.layout: SequenceLayout = None
        self.teacher_mode = False

        # Two inference-only levels, separated so a benchmark can attribute the speedup.
        # `hybrid_inference_mode` covers only work intrinsic to the hybrid algorithm:
        # the FLASH window kernel and the tuned linear far branch. `inference_mode`
        # additionally enables general fusions such as QK-norm + RoPE. The production
        # setter turns both on; defaults stay slow-but-correct for training and forgotten
        # switches.
        self.hybrid_inference_mode = False
        self.inference_mode = False
        d_linear = linear_head_dim or self.head_dim
        self.linear_attention = BidirectionalLinearBranch(
            hidden_size, self.num_heads, d_linear, delta_rule=delta_rule, bridge=bridge,
            a_fp32=a_fp32, short_conv=short_conv)
        # The linear branch's own output projection, torch-default init: the readout it
        # consumes is SiLU'd and RMS-normalised, so there is no reason to seed it from
        # orig.to_out. Stage A1 trains it from scratch.
        self.to_out_linear = nn.Linear(self.num_heads * d_linear, hidden_size,
                                       bias=False)
        self.enable_softmax_gate = enable_softmax_gate
        if enable_softmax_gate:
            # per-head, direct (not low rank). 0.99 keeps the softmax branch at the
            # teacher on step 0.
            self.softmax_gate = OutputGate(hidden_size, self.num_heads, init_value=0.99)

    def _qkv(self, x, rotary_emb):
        """Replicates MiniMaxH3AttnProcessor up to (and excluding) the attention call,
        via the original module's submodules — projections (LoRA-wrapped ones apply),
        QK-norm and RoPE included. Also returns the raw (pre-QK-norm, pre-RoPE) q/k/v
        for the shared-QKV linear branch. x: [total, hidden]; everything [total, H, d].
        Under fp8 the three projections share one quantisation of x.

        Inference runs QK-norm + rope as ONE kernel (`_qk_prep`, not bitwise); training
        keeps the eager ops the checkpoints were trained under."""
        orig = self.orig
        projections = (orig.to_q, orig.to_k, orig.to_v)

        if all(isinstance(p, Fp8Linear) for p in projections):
            x_fp8, x_scale = quantize_activation(x)
            qkv = [p.forward_quantized(x_fp8, x_scale, out_dtype=x.dtype) for p in projections]
        else:
            qkv = [p(x) for p in projections]

        query_raw, key_raw, value = (t.unflatten(-1, (orig.heads, -1)) for t in qkv)  # [total, H, d]

        if self.inference_mode and rotary_emb is not None:
            query = _qk_prep(query_raw, orig.norm_q.weight, orig.norm_q.eps, *rotary_emb)
            key = _qk_prep(key_raw, orig.norm_k.weight, orig.norm_k.eps, *rotary_emb)
        else:
            query, key = orig.norm_q(query_raw), orig.norm_k(key_raw)
            if rotary_emb is not None:
                query = _apply_rotary_emb(query.unsqueeze(0), *rotary_emb).squeeze(0)
                key = _apply_rotary_emb(key.unsqueeze(0), *rotary_emb).squeeze(0)

        return query, key, value, (query_raw, key_raw, value)

    def _bounds(self, layout):
        return window_bounds(layout.num_frames, self.radius, self.chunk)

    def forward(self, hidden_states, rotary_emb=None, attention_mask=None):
        if attention_mask is not None:
            raise ValueError("H3 packs one request per document; no attention mask expected.")
        if hidden_states.shape[0] != 1:
            raise ValueError("HybridAttention assumes batch 1 (one packed document).")

        if self.teacher_mode:
            out = self.orig(hidden_states, rotary_emb, attention_mask)
        else:
            out = self._hybrid_forward(hidden_states[0], rotary_emb).unsqueeze(0)

        return out

    def _window_kernel(self, inference, on_cuda):
        """Which window-softmax kernel this forward runs. `softmax_impl` is the process-wide
        choice (hybrid_transform.set_softmax_backend); the decomposition is inference-only,
        training keeps the differentiable flex path."""
        if not on_cuda or self.softmax_impl == "ref":
            return "ref"
        if self.softmax_impl == "decomposed" and inference:
            return "decomposed"
        return "flex"

    def _window_softmax(self, query, key, value, layout, bounds, scale, inference):
        kernel = self._window_kernel(inference, query.is_cuda)
        if kernel == "decomposed":
            return window_softmax_decomposed(query, key, value, layout, bounds, scale,
                                             anchor_frames=self.anchor_frames)
        if kernel == "flex":
            block_mask = build_window_block_mask(layout, bounds, value.device,
                                                 anchor_frames=self.anchor_frames)
            return window_softmax_flex(query, key, value, block_mask, scale,
                                       inference=inference)
        return window_softmax_reference(query, key, value, layout, bounds, scale,
                                        anchor_frames=self.anchor_frames)

    def _hybrid_forward(self, x, rotary_emb):
        layout = self.layout
        hybrid_inference = self.hybrid_inference_mode or self.inference_mode
        bounds = self._bounds(layout) if layout is not None else None
        full_cover = layout is None or all(
            lo <= 0 and hi >= layout.num_frames - 1 for lo, hi in bounds)
        scale = self.head_dim ** -0.5

        if not full_cover and self._window_kernel(hybrid_inference, x.is_cuda) == "flex":
            # Built (once; cached) BEFORE the projections exist: torch's create_block_mask
            # materialises ~10 GiB at 89k rows, and here the layer's live set is x alone
            # rather than x plus 7 GiB of raw and roped q/k/v.
            build_window_block_mask(layout, bounds, x.device, anchor_frames=self.anchor_frames)

        query, key, value, qkv_raw = self._qkv(x, rotary_emb)
        if full_cover:
            # A window wide enough to cover every frame IS the original attention, so go
            # through the stock processor's own dispatch rather than a bare SDPA call:
            # two different bf16 attention kernels over ~100k keys differ by far more
            # than the 0.99 gate contributes. Matching the kernel makes the full-cover
            # path exactly the teacher.
            softmax_out = dispatch_attention_fn(
                query.unsqueeze(0), key.unsqueeze(0), value.unsqueeze(0),
                attn_mask=None, dropout_p=0.0, is_causal=False,
                backend=getattr(type(self.orig.processor), "_attention_backend", None),
            ).squeeze(0)
            # nothing lies outside the window, so the linear branch would double count
            linear_active = False
        else:
            softmax_out = self._window_softmax(query, key, value, layout, bounds, scale,
                                               hybrid_inference)
            linear_active = True
            if self._window_kernel(hybrid_inference, x.is_cuda) == "flex":
                collect_after_first_flash()      # see flex_attention: a one-time gc

        # The roped q/k (and the flex output) are dead once the local branch is done;
        # drop them before the linear branch runs — at H3 scale they are ~3 GiB that would
        # otherwise sit under the linear branch's own peak.
        del query, key, value
        if self.enable_softmax_gate:
            flat = apply_softmax_gate(softmax_out, self.softmax_gate(x),
                                     inference=self.inference_mode)
        else:
            flat = softmax_out.reshape(x.shape[0], -1)
        out = self.orig.to_out[0](flat.type_as(x))
        out = self.orig.to_out[1](out)
        del softmax_out

        if linear_active and self.linear_attention_enabled:
            video_start, video_end = layout.video_start, layout.video_end
            video_x = x[video_start:video_end]
            video_qkv_raw = tuple(t[video_start:video_end] for t in qkv_raw)
            text_x = text_qkv_raw = None
            if self.enable_text_state:
                text_start, text_end = layout.text_range
                text_x = x[text_start:text_end]
                text_qkv_raw = tuple(t[text_start:text_end] for t in qkv_raw)

            # The grid is only DEMANDED when the conv exists: layout.frame_size raises
            # on grid-less layouts, and every conv-less config must keep working with
            # them (only frame_size consumers are gated on short_conv).
            linear_readout = self.linear_attention(video_x, layout.num_frames, layout.tokens_per_frame,
                                   bounds, qkv_raw=video_qkv_raw,
                                   frame_size=(layout.frame_size
                                               if self.linear_attention.short_conv is not None
                                               else None),
                                   skip_ends=self.anchor_frames == "both",
                                   text_x=text_x, text_qkv_raw=text_qkv_raw,
                                   inference=hybrid_inference)

            # The clone is autograd's: `out` is the output of self.orig.to_out[1], and
            # writing into it in place would corrupt what backward needs. With no graph
            # to protect there is nothing to copy -- and at H3 scale this tensor is
            # [~105k, 5376] bf16 = 1.05 GiB, copied once per layer per denoising step.
            if torch.is_grad_enabled():
                out = out.clone()
            out[video_start:video_end] += self.to_out_linear(linear_readout.type_as(x))
        return out


